// ---- IDM 跟车模型(Intelligent Driver Model)-------------------------
//
// 原来的纵向模型是 `speed += (cruise - speed) * approach`:一个朝巡航速度
// 的指数逼近,**没有任何前车感知**。前车停住时它照开不误 —— 数值实测
// 前车停在 30 m 外,t = 2.60 s 就撞上去,一次都不减速。
//
// IDM(`a = a_max [1 - (v/v0)^delta - (s*/s)^2]`)给出真实跟车行为:
// 自由流趋近巡航,靠近前车时平顺减速,间距稳定在 `s*` 附近。

/// IDM 的期望最小车距(米)。
///
/// `s0` 是静止时的安全间距(约两个车头),`T` 是期望时间间隔。两者相加
/// 就是稳态跟车距离:11.5 m/s + 1.5 s 时距 ≈ 20 m。
pub(crate) const IDM_MIN_GAP: f32 = 2.6;

/// IDM 的期望时间间隔(秒)。
///
/// 城市道路按 1.5 s 取:车距 11.5 m/s × 1.5 s ≈ 17 m,加上 2.6 m 静止
/// 间距,稳态 20 m。真实驾驶员在市区大致是这个量级。
pub(crate) const IDM_HEADWAY: f32 = 1.5;

/// IDM 的最大加速度(米/秒²)—— 自由流时追巡航速度的加速度。
pub(crate) const IDM_ACCEL_MAX: f32 = 4.0;

/// IDM 的舒适减速度(米/秒²)。
///
/// 真实车辆的最大制动约 8–9 m/s²,但 IDM 的 `b` 是**舒适**减速度,只在
/// 极端跟车时用到;取 6.0 让急刹仍然跟得上物理刹车的手感。
pub(crate) const IDM_BRAKE_COMFORT: f32 = 6.0;

/// IDM 速度差的指数(固定为 4)。
///
/// 学术标准值。取 4 时 `s* = s0 + max(0, v*T + v*dv/(2*sqrt(a*b)))`,
/// 前车更快(`dv < 0`)时 `s*` 反而变大 —— 于是**别人插到你前面你会
/// 自动减速让出空间**,而不是撞上去。
pub(crate) const IDM_DELTA: f32 = 4.0;

/// IDM 的加速度下限(米/秒²)—— 避免 a 变负得没完,把车推成倒车。
pub(crate) const IDM_ACCEL_MIN: f32 = -9.0;

// ---- 红绿灯相位 ------------------------------------------------------
//
// 南北 / 东西两套相位交替,每轮都带**全红**间隔:两个方向同时放行会让车
// 在路口中央对撞,而直接切换的一瞬间已经进路口的车会被困在「两个都是
// 红」的中间态。

/// 一个方向的绿灯时长(秒)。
///
/// 真实路口绿灯 15–30 s。这里取 12 s —— 一个 60 m 的街块以巡航 11.5 m/s
/// 只需要 5 s 就跑完,12 s 足够放行车队里的前几辆,又不至于让玩家干等。
pub(crate) const SIGNAL_GREEN_SECONDS: f32 = 12.0;

/// 全红间隔时长(秒)。
///
/// **由刹车距离反推,不是拍脑袋。** 11.5 m/s 的车用 IDM 舒适减速
/// (`b = 6.0`)停住要 `v/b` = **1.92 s**、约 11 m。红灯窗口比刹车时间短,
/// 车就会「明明要停却停不下来」直接压过去 —— 实测过:全红 1.6 s 时,
/// 距线 6.7 m 的车在 0.93 s 内冲到 50.74 m,停止线在 50.717,**压线 0.02 m**。
///
/// 取 **4.0 s**:覆盖 `SIGNAL_BRAKE_LOOKAHEAD`(30 m)内任意位置起步的车
/// 都能停住(30 m 处 11.5 m/s 的车刹车时间是 2.6 s,余量 1.4 s),也给
/// 已经进路口的车留出清空时间。
pub(crate) const SIGNAL_ALL_RED_SECONDS: f32 = 4.0;

/// 黄灯时长(秒)。
///
/// 3 s:11.5 m/s 时正好 34.5 m,超过一个街块。取短一点是为了让「黄灯」
/// 在 60 s 的观察窗口里能真正看到,不只是一瞬间。
pub(crate) const SIGNAL_AMBER_SECONDS: f32 = 3.0;

/// 信号机的完整周期(秒)。
pub(crate) const SIGNAL_CYCLE_SECONDS: f32 =
    2.0 * (SIGNAL_GREEN_SECONDS + SIGNAL_AMBER_SECONDS + SIGNAL_ALL_RED_SECONDS);

/// 停止线离路口中轴线的距离(米)。
///
/// 车要停在**路口之前**而不是中心上。路口半宽加一条车身的缓冲:
/// 停止线必须在车头碰到对面来车之前就拦住它。
///
/// `2.283` 是 [`CAR_FOOTPRINT`](../collision/const.rs 的半车长)。写成字面量
/// 而不是跨模块引用:traffic 的 `const.rs` 拿不到 collision 的常量,而
/// `impl.rs` 拿得到 —— 同一个名字在两个文件里的可见性不同。
pub(crate) const SIGNAL_STOP_OFFSET: f32 = 7.0 + 2.283;

/// 限速公式的余量系数。
///
/// `sqrt(2·b·gap)` 是「刚好停得住」的临界速度,贴着它跑会在最后几帧抖动
/// —— 一帧算得停得住、下一帧因为浮点误差算不住,车就在线上前后蹭。
/// 乘 0.9 留出 10% 余量。
pub(crate) const SIGNAL_CAP_MARGIN: f32 = 0.9;

/// 停止线前多远开始**强制停死**(米)。
///
/// `sqrt(2·b·gap)` 的限速有一个爬行平衡点(`a = 0` 但 `v ≠ 0`),车会停在
/// 离线两米的地方以 0.05 m/s 往前蹭。这个阈值内直接要求 `v = 0`。
///
/// 取 **1.5 m**:大于半车长(2.283 / 2 = 1.14 m),所以车停稳时车头一定
/// 在线外;又不至于让刹车曲线在最后几帧突然变平。
pub(crate) const SIGNAL_CAP_FLOOR_GAP: f32 = 1.5;

/// 车距离停止线多远就开始刹车(米)。
///
/// 不能等到了线才停 —— 11.5 m/s 需要约 18 m 才停得住(IDM 舒适减速
/// 6 m/s² 给出 11 m,留一倍余量)。
pub(crate) const SIGNAL_BRAKE_LOOKAHEAD: f32 = 30.0;

/// `pickup_health_pack` 的回血量(点)。
pub(crate) const HEALTH_PACK_HEAL: f32 = 35.0;

/// `pickup_cash_stack` 的金额。
pub(crate) const CASH_STACK_AMOUNT: f32 = 250.0;

/// 拾取物绕 Y 轴的自转角速度(弧度/秒)。
pub(crate) const PICKUP_SPIN_RATE: f32 = 1.1;

// ---- 车队路网:车怎么在街道网格上选路 -------------------------------
//
// 一辆车在网格上有一个**所在街道索引**(`street`)与**所在车道侧**
// (`side` = −1 / +1,即街道中轴线两侧各一条车道),外加一个**行进轴**
// (`axis`)。`axis = 0` 表示沿 Z 走(车位于一条南北向街道上),
// `axis = 1` 表示沿 X 走(车位于一条东西向街道上)。
//
// 走法:沿当前车道开到下一个路口,然后要么直行(街道索引 +1,车道侧翻转,
// 因为双向车道),要么转向(切到另一条街道上去,车道侧保持)。转向时按
// [`ROUTE_PICK`] 抽签,让车流不会全城一个方向。
/// 车队在路口选择「转向」而不是「直行」的概率(0..1)。
///
/// 0.62 让每个路口平均每 1.6 次就转一次弯,弯多到一眼看得出是路口,
/// 又不至于整条街的车都挤进同一个街区。直行的那部分仍占 38%,于是
/// 纵向街道上仍然有连续可见的车流。
pub(crate) const ROUTE_PICK: f32 = 0.62;

/// AI 车每步推进的子步长(米)—— 与 [`CAR_FOOTPRINT`] 配套。
///
/// 数值取自 [`CAR_STEP`]:车长 4.566 m,而世界里最薄的静态碰撞体只有
/// 0.133 m(交通锥),一帧走 1.6 m 足以整个跳过它。子步保证任何单步
/// 位移都短于最薄障碍 —— 那是「车不再穿楼」的最后一道保证。
/// 「这一步其实没走成」的判定余量(米)。
///
/// 位移被碰撞吃掉时,判定为撞上障碍:车停下、速度归零、路网状态不推进。
/// 余量必须小于单帧位移,否则正常行驶也会被误判成撞墙。
pub(crate) const CAR_ROUTE_EPSILON: f32 = 0.001;
