// ===========================================================================
// 武器
// ===========================================================================
/// 三种可切换武器。
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Weapon {
    /// 手枪:精度高、射速中等、弹匣小。
    Pistol,
    /// 冲锋枪:射速快、伤害低、弹匣大。
    Smg,
    /// 球棒:近战、无弹药、一击重创。
    Bat,
    /// 手雷:抛投型,范围伤害。
    Grenade,
    /// 徒手:没拿武器(GTA V 按 H 收起武器后的状态)。
    ///
    /// **不是新增玩法,是给「收起」一个可表示的状态。** 之前按 H 无处
    /// 可去,原因是 `Weapon` 里根本没有「手上没东西」这一档,`weapon_mesh`
    /// 只能指向某个真实模型。加了这个变体之后 H 才有地方落。
    Unarmed,
}

// ===========================================================================
// 敌人 AI
// ===========================================================================
/// 敌人的行为状态。
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AiState {
    /// 站桩不动(出生后的第一帧)。
    Idle,
    /// 沿出生点附近小范围游荡。
    Patrol,
    /// 看见玩家,正在靠近。
    Chase,
    /// 已在射程内,正在开火。
    Attack,
    /// 血量见底,转身逃跑。
    Flee,
    /// 已死亡,尸体下沉中。
    Dead,
}

/// 敌人是警察还是敌对混混。
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Faction {
    /// 警察:被通缉触发,攻击玩家,不掉通缉热度。
    Police,
    /// 敌对混混:自由巡逻,被攻击后反击。
    Thug,
}
