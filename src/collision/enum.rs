use super::*;

/// 一个静态碰撞体(投影到世界 XZ 平面)。
#[derive(Clone, Copy, Debug)]
pub enum Shape {
    /// 轴对齐包围盒 —— 建筑 / 车辆 / 长椅这类方块状道具。
    Aabb {
        /// 盒中心的世界 XZ 坐标。
        center: Vec2,
        /// 盒的半尺寸(世界 XZ,米)。
        half: Vec2,
    },
    /// 竖直圆柱 —— 棕榈 / 垃圾桶 / 消防栓这类近似圆形的道具。
    Circle {
        /// 圆柱中心的世界 XZ 坐标。
        center: Vec2,
        /// 圆柱半径(米)。
        radius: f32,
    },
    /// 有向盒(OBB)—— 旋转过的楼。
    ///
    /// **为什么不能只用 `Aabb`:** 二维世界原本只有轴对齐盒,而斜放的
    /// 楼(`yaw = -π/4` 的路口对角楼)只能退化成它的**外接 AABB** ——
    /// 45° 时每条边多出 `(√2 − 1) ≈ 41%` 的长度,于是楼与楼之间、
    /// 楼与人行道之间凭空多出一圈矩形。实测 `bldg_cream_block`
    /// (局部半尺寸 10.26 × 9.10)斜放后 AABB 半尺寸变成 13.71 × 13.71,
    /// 每个角上多出约 2.7 m × 2.7 m 的**空气墙**:人走不过去、车撞上
    /// 一堵看不见的墙,画面上却空空如也(用户报「有的建筑可以穿过去」
    /// ——那是反过来的另一批:AABB 比真实楼体小的地方)。
    ///
    /// 在**局部坐标系**里 OBB 就是 AABB:把点转回 `yaw` 的负角、比较半长,
    /// 于是所有已有的盒算法(解析、射线、分离)可以直接复用,只有
    /// 「世界 ↔ 局部」这一层需要额外两步三角函数。
    Obb {
        /// 盒中心的世界 XZ 坐标。
        center: Vec2,
        /// 盒的半尺寸(**沿盒自身坐标轴**,米)。
        half: Vec2,
        /// 绕 Y 轴的朝向(弧度)。
        yaw: f32,
    },
}

/// 一个动态碰撞体的**身份**。
///
/// 分离力的大小按质量比分配(见 [`CollisionWorld::resolve_dynamic`]),
/// 所以「谁在撞谁」必须可判定 —— 同一类实体之间同样要分开,否则两个人
/// 走在一起会互相穿过去。
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum BodyKind {
    /// 玩家角色。
    Player,
    /// 交通车辆。
    Car,
    /// 行人。
    Pedestrian,
    /// 敌对 / 警察 NPC。
    Enemy,
}
